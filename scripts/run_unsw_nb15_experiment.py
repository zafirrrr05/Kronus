#!/usr/bin/env python3
"""UNSW-NB15 Independent ML Experiment for KRONUS.

EXPERIMENT: UNSW-NB15 External Dataset
======================================
This script trains fresh, independent KRONUS Bouncer and Detective models
using the UNSW-NB15 intrusion detection dataset (Australian Centre for Cyber
Security, UNSW Canberra).

Dataset URL: https://research.unsw.edu.au/projects/unsw-nb15-dataset

DATASET CHARACTERISTICS
-----------------------
UNSW-NB15 was generated by the IXIA PerfectStorm tool, producing a hybrid of
real modern normal activity and synthetic contemporary attack traffic. Unlike
CIC-IDS2017 (all-benign + DDoS days), UNSW-NB15 carries a genuine
Reconnaissance class, so BOTH KRONUS detection lanes can be trained here:

  - DoS            (12,264 rows in train)  -> Label.FLOOD      (Bouncer)
  - Reconnaissance (10,491 rows in train)  -> Label.PORT_SCAN  (Detective)
  - Normal         (56,000 rows in train)  -> Label.BENIGN
  - Generic, Exploits, Fuzzers, Analysis, Backdoor, Shellcode, Worms
                   -> no clean KRONUS label (generic non-benign signal)

HOST RECONSTRUCTION (honest disclosure)
---------------------------------------
The author-supplied pre-split CSVs used here carry NO IP addresses and NO port
numbers. Source/destination hosts are reconstructed deterministically from each
row's own recorded connection-rate counters, following the same approach (and
the same category-aware clustering rule) as twin/nsl_kdd.py. This is recorded
in the metrics as "synthetic_hosts": true — the flow FEATURES are real, the
graph TOPOLOGY is reconstructed. See twin/unsw_nb15.py for the full rationale.

EXPERIMENT DESIGN
-----------------
Models are trained INDEPENDENTLY from scratch on UNSW-NB15 data -- zero weight
inheritance from NSL-KDD or CIC-IDS2017 models.

Feature extraction and graph building use the identical production telemetry
pipeline (FlowFeaturizer and WindowedGraphBuilder). The window construction
matches the existing external-dataset runners (run_cic_experiment.py):
per-class stratified split, then per-class snapshot pools.

TRAIN/TEST SPLIT:
  Stratified 67/33 split by class, seeded for reproducibility.
  Disjoint index-level splits ensure zero data leakage.

WEIGHT ARTIFACTS:
  models/experiments/unsw_nb15/bouncer/   (bouncer.json, calibration.json)
  models/experiments/unsw_nb15/detective/ (detective.npz, detective.onnx)

METRICS:
  results/experiments/unsw_nb15_metrics.json
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

opa_bin = REPO_ROOT / "bin" / "opa"
if opa_bin.exists():
    os.environ["KRONUS_OPA_BINARY"] = str(opa_bin)
    os.environ["PATH"] = f"{REPO_ROOT / 'bin'}:{os.environ.get('PATH', '')}"

import numpy as np
from sklearn.metrics import confusion_matrix, precision_recall_fscore_support

from libs.constants import Label
from libs.schemas import GraphEdge, GraphNode, GraphSnapshot
from services.bouncer.features import FEATURE_NAMES, FlowFeaturizer
from services.bouncer.model import BouncerModel
from services.detective.model import DetectiveModel
from services.graph_builder.builder import WindowedGraphBuilder
from services.telemetry_exporter.converters import flow_row_to_event
from twin.unsw_nb15 import load_unsw_nb15

DATA_DIR = REPO_ROOT / "data" / "external" / "unsw_nb15"
MODELS_DIR = REPO_ROOT / "models" / "experiments" / "unsw_nb15"
BOUNCER_DIR = MODELS_DIR / "bouncer"
DETECTIVE_DIR = MODELS_DIR / "detective"
RESULTS_DIR = REPO_ROOT / "results" / "experiments"
METRICS_PATH = RESULTS_DIR / "unsw_nb15_metrics.json"

DATASET_URL = "https://research.unsw.edu.au/projects/unsw-nb15-dataset"
DATASET_SOURCE = "UNSW-NB15 (Australian Centre for Cyber Security, UNSW Canberra)"

T0 = datetime(2025, 2, 14, 12, 0, 0, tzinfo=timezone.utc)
ROW_SPACING_MS = 20
TRAIN_RATIO = 0.67
SEED = 42


def _build_bouncer_features(rows: list, label: int) -> tuple[np.ndarray, np.ndarray]:
    """Replay rows through the live FlowFeaturizer.

    Rows are ordered by source_ip before replay so that a given source's
    traffic is contiguous — that is what makes the featurizer's sliding-window
    aggregates (event_rate, unique_dest_count, same_dest_ratio) reflect a real
    host's behaviour rather than a shuffle artifact.
    """
    rows = sorted(rows, key=lambda r: r.source_ip)
    featurizer = FlowFeaturizer()
    X = []
    for i, row in enumerate(rows):
        event = flow_row_to_event(row, ts=T0 + timedelta(milliseconds=i * ROW_SPACING_MS))
        feats = featurizer.features_for(event)
        X.append([feats[name] for name in FEATURE_NAMES])
    if not X:
        return np.empty((0, len(FEATURE_NAMES))), np.empty((0,), dtype=int)
    return np.array(X), np.full(len(X), label)


def _build_graph_snapshots(rows: list, label: Label) -> list[tuple]:
    """Build windowed graph snapshots for GAT training.

    Matches the construction used by the existing external-dataset runners
    (scripts/run_cic_experiment.py::_build_graph_snapshots) so results are
    directly comparable across experiments.
    """
    builder = WindowedGraphBuilder(window_seconds=2.0)
    labeled = []
    for i, row in enumerate(rows):
        ts = T0 + timedelta(milliseconds=i * ROW_SPACING_MS)
        snap = builder.ingest(flow_row_to_event(row, ts=ts))
        if snap is not None and snap.edges:
            labeled.append((snap, label))
    final_ts = T0 + timedelta(milliseconds=len(rows) * ROW_SPACING_MS)
    final = builder.flush(end_time=final_ts)
    if final is not None and final.edges:
        labeled.append((final, label))
    return labeled


def _stratified_split(items: list, ratio: float, seed: int) -> tuple[list, list]:
    rng = np.random.default_rng(seed)
    idx = rng.permutation(len(items)).tolist()
    n_train = int(len(idx) * ratio)
    train_idx = set(idx[:n_train])
    train = [items[i] for i in range(len(items)) if i in train_idx]
    test = [items[i] for i in range(len(items)) if i not in train_idx]
    return train, test


def train_bouncer(rows: list, seed: int, limit: int | None = None) -> tuple[BouncerModel | None, dict]:
    """Train Bouncer independently on UNSW-NB15: DoS (flood) vs Normal."""
    flood_rows = [r for r in rows if r.category == "dos"]
    normal_rows = [r for r in rows if r.category == "normal"]

    if not flood_rows or not normal_rows:
        return None, {
            "skipped": "UNSW-NB15 subset lacks both DoS (flood) and Normal rows",
            "n_dos": len(flood_rows),
            "n_normal": len(normal_rows),
        }

    if limit is not None and limit > 0:
        flood_rows = flood_rows[:limit]
        normal_rows = normal_rows[:limit]

    flood_train, flood_test = _stratified_split(flood_rows, TRAIN_RATIO, seed)
    normal_train, normal_test = _stratified_split(normal_rows, TRAIN_RATIO, seed + 1)

    X_tr = np.vstack([
        _build_bouncer_features(flood_train, 1)[0],
        _build_bouncer_features(normal_train, 0)[0],
    ])
    y_tr = np.concatenate([
        np.ones(len(flood_train), dtype=int),
        np.zeros(len(normal_train), dtype=int),
    ])
    X_te = np.vstack([
        _build_bouncer_features(flood_test, 1)[0],
        _build_bouncer_features(normal_test, 0)[0],
    ])
    y_te = np.concatenate([
        np.ones(len(flood_test), dtype=int),
        np.zeros(len(normal_test), dtype=int),
    ])

    print(f"  Bouncer train: {len(y_tr)} rows (flood={int(y_tr.sum())}, normal={int((y_tr==0).sum())})")
    print(f"  Bouncer test:  {len(y_te)} rows (flood={int(y_te.sum())}, normal={int((y_te==0).sum())})")

    t0 = time.perf_counter()
    model = BouncerModel()
    model.fit(X_tr, y_tr)
    train_time = time.perf_counter() - t0

    proba = model.predict_proba(X_te)
    y_pred = (proba >= 0.5).astype(int)
    prec, rec, f1, _ = precision_recall_fscore_support(y_te, y_pred, average="binary", zero_division=0)
    acc = float((y_pred == y_te).mean())
    cm = confusion_matrix(y_te, y_pred, labels=[0, 1]).tolist()

    BOUNCER_DIR.mkdir(parents=True, exist_ok=True)
    model.save(BOUNCER_DIR)

    metrics = {
        "component": "bouncer",
        "training_origin": "unsw_nb15",
        "dataset_source": DATASET_SOURCE,
        "dataset_url": DATASET_URL,
        "model_type": "XGBoost + Temperature Scaling (trained from scratch)",
        "task": "binary DoS-flood vs benign classification",
        "synthetic_hosts": True,
        "seed": seed,
        "train_ratio": TRAIN_RATIO,
        "n_train": int(len(y_tr)),
        "n_test": int(len(y_te)),
        "n_train_attack": int(y_tr.sum()),
        "n_train_normal": int((y_tr == 0).sum()),
        "n_test_attack": int(y_te.sum()),
        "n_test_normal": int((y_te == 0).sum()),
        "train_seconds": round(train_time, 3),
        "accuracy": round(acc, 4),
        "precision": round(float(prec), 4),
        "recall": round(float(rec), 4),
        "f1": round(float(f1), 4),
        "confusion_matrix": cm,
        "features": FEATURE_NAMES,
        "weight_artifacts": [
            str(BOUNCER_DIR / "bouncer.json"),
            str(BOUNCER_DIR / "calibration.json"),
        ],
    }
    print(f"  Bouncer (UNSW-NB15): Acc={acc:.4f} Prec={prec:.4f} Rec={rec:.4f} F1={f1:.4f}")
    return model, metrics


def train_detective(rows: list, seed: int, limit: int | None = 10_000) -> tuple[DetectiveModel | None, dict]:
    """Train Detective independently on UNSW-NB15 graph snapshots: Recon vs Normal."""
    normal_rows = [r for r in rows if r.category == "normal"]
    probe_rows = [r for r in rows if r.category == "probe"]

    if not normal_rows or not probe_rows:
        return None, {
            "skipped": "UNSW-NB15 subset lacks both Normal and Reconnaissance rows",
            "n_normal": len(normal_rows),
            "n_probe": len(probe_rows),
        }

    if limit is not None and limit > 0:
        normal_rows = normal_rows[:limit]
        probe_rows = probe_rows[:limit]

    norm_train, norm_test = _stratified_split(normal_rows, TRAIN_RATIO, seed)
    probe_train, probe_test = _stratified_split(probe_rows, TRAIN_RATIO, seed + 1)

    train_snaps = (
        _build_graph_snapshots(norm_train, Label.BENIGN) +
        _build_graph_snapshots(probe_train, Label.PORT_SCAN)
    )
    test_snaps = (
        _build_graph_snapshots(norm_test, Label.BENIGN) +
        _build_graph_snapshots(probe_test, Label.PORT_SCAN)
    )

    print(f"  Detective train windows: {len(train_snaps)}")
    print(f"  Detective test  windows: {len(test_snaps)}")

    if not train_snaps:
        return None, {"skipped": "No graph windows produced from UNSW-NB15 train rows"}

    t0 = time.perf_counter()
    model = DetectiveModel(rng=np.random.default_rng(seed))
    epochs, batch_size = 4, 4
    for ep in range(epochs):
        rng = np.random.default_rng(seed + ep)
        order = rng.permutation(len(train_snaps))
        ep_loss, nb = 0.0, 0
        for si in range(0, len(order), batch_size):
            batch = [train_snaps[i] for i in order[si : si + batch_size]]
            ep_loss += model.train_batch(batch, learning_rate=0.02, momentum=0.9)
            nb += 1
        print(f"  Epoch {ep + 1}/{epochs}  avg_loss={ep_loss / max(nb, 1):.4f}")
    train_time = time.perf_counter() - t0

    if not test_snaps:
        return model, {"skipped": "No graph windows produced from UNSW-NB15 test rows"}

    y_true, y_pred = [], []
    for snap, lbl in test_snaps:
        v = model.predict_verdict(snap, window_id=snap.window_id)
        y_true.append(lbl.value)
        y_pred.append(v.label if v.label != Label.UNCERTAIN.value else "port_scan")

    labels = ["benign", "port_scan"]
    acc = float(np.mean([a == b for a, b in zip(y_true, y_pred, strict=True)]))
    prec, rec, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=labels, average="macro", zero_division=0
    )
    cm = confusion_matrix(y_true, y_pred, labels=labels).tolist()

    DETECTIVE_DIR.mkdir(parents=True, exist_ok=True)
    model.save(DETECTIVE_DIR)

    metrics = {
        "component": "detective",
        "training_origin": "unsw_nb15",
        "dataset_source": DATASET_SOURCE,
        "dataset_url": DATASET_URL,
        "model_type": "GAT in autograd (trained from scratch)",
        "task": "macro benign vs port_scan graph window classification",
        "synthetic_hosts": True,
        "seed": seed,
        "train_ratio": TRAIN_RATIO,
        "train_windows": len(train_snaps),
        "test_windows": len(test_snaps),
        "train_seconds": round(train_time, 3),
        "accuracy": round(acc, 4),
        "precision": round(float(prec), 4),
        "recall": round(float(rec), 4),
        "f1": round(float(f1), 4),
        "confusion_matrix": cm,
        "weight_artifacts": [
            str(DETECTIVE_DIR / "detective.npz"),
            str(DETECTIVE_DIR / "detective.onnx"),
        ],
    }
    print(f"  Detective (UNSW-NB15): Acc={acc:.4f} Prec={prec:.4f} Rec={rec:.4f} F1={f1:.4f}")
    return model, metrics


def verify_weights() -> dict:
    """Verify saved models load cleanly and execute correct inference."""
    results = {}
    bouncer_ok = False
    try:
        b = BouncerModel.load(BOUNCER_DIR)
        feats = {n: 10.0 for n in FEATURE_NAMES}
        v = b.predict_verdict(feats, window_id="verify-unsw-bouncer")
        bouncer_ok = v is not None and 0.0 <= v.confidence <= 1.0
        print(f"  UNSW-NB15 Bouncer load: {'PASSED' if bouncer_ok else 'FAILED'} (verdict={v.label}, conf={v.confidence:.3f})")
    except Exception as exc:
        print(f"  UNSW-NB15 Bouncer load FAILED: {exc}")
    results["unsw_nb15_bouncer_loadable"] = bouncer_ok

    detective_ok = False
    try:
        d = DetectiveModel.load(DETECTIVE_DIR)
        now = datetime.now(timezone.utc)
        snap = GraphSnapshot(
            window_id="verify-unsw-detective",
            window_start=now,
            window_end=now,
            nodes=[
                GraphNode(node_id="10.10.100.1", degree_in=0.0, degree_out=2.0, bytes_total=500.0, unique_ports_contacted=2),
                GraphNode(node_id="10.20.100.1", degree_in=2.0, degree_out=0.0, bytes_total=500.0, unique_ports_contacted=0),
            ],
            edges=[
                GraphEdge(src="10.10.100.1", dst="10.20.100.1", bytes=500.0, flow_count=2, port_entropy=0.5, duration_mean_ms=15.0),
            ],
        )
        v = d.predict_verdict(snap, window_id="verify-unsw-detective")
        detective_ok = v is not None and 0.0 <= v.confidence <= 1.0
        print(f"  UNSW-NB15 Detective load: {'PASSED' if detective_ok else 'FAILED'} (verdict={v.label}, conf={v.confidence:.3f})")
    except Exception as exc:
        print(f"  UNSW-NB15 Detective load FAILED: {exc}")
    results["unsw_nb15_detective_loadable"] = detective_ok
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--limit", type=int, default=10_000,
                        help="max rows per class for the Detective window pools")
    parser.add_argument("--bouncer-limit", type=int, default=20_000,
                        help="max rows per class for Bouncer training")
    parser.add_argument("--sample-per-file", type=int, default=0,
                        help="optional cap on rows read per CSV (0 = all)")
    args = parser.parse_args()

    print("=" * 70)
    print("UNSW-NB15 INDEPENDENT TRAINING & EVALUATION")
    print("=" * 70)

    if not DATA_DIR.exists():
        print(f"Dataset directory not found: {DATA_DIR}")
        print("Run: python scripts/download_unsw_nb15.py")
        return 1

    print(f"Loading UNSW-NB15 flows from {DATA_DIR} ...")
    t0 = time.perf_counter()
    rows = load_unsw_nb15(DATA_DIR, sample_per_file=args.sample_per_file or None)
    load_time = time.perf_counter() - t0

    cats: dict[str, int] = {}
    for r in rows:
        cats[r.category] = cats.get(r.category, 0) + 1
    print(f"  Loaded {len(rows):,} flows in {load_time:.2f}s")
    print(f"  Category distribution: {cats}")

    if not rows:
        print("No rows loaded — nothing to train on. Aborting without writing metrics.")
        return 1

    print("\n--- Training Bouncer (XGBoost + TemperatureScaler) on UNSW-NB15 ---")
    bouncer_model, bouncer_metrics = train_bouncer(rows, seed=SEED, limit=args.bouncer_limit)

    print("\n--- Training Detective (GAT in autograd) on UNSW-NB15 ---")
    detective_model, detective_metrics = train_detective(rows, seed=SEED, limit=args.limit)

    print("\n--- Verifying Weight Loadability & Live Inference ---")
    weight_verification = verify_weights()

    full_metrics = {
        "experiment": "unsw_nb15",
        "status": "COMPLETE",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "dataset": {
            "source": DATASET_SOURCE,
            "url": DATASET_URL,
            "total_flows": len(rows),
            "category_distribution": cats,
            "synthetic_hosts": True,
            "synthetic_hosts_note": (
                "The author-supplied UNSW-NB15 pre-split CSVs carry no IP addresses "
                "or port numbers. Source/destination hosts are reconstructed "
                "deterministically from each row's own connection-rate counters "
                "(twin/unsw_nb15.py). Flow FEATURES are real; graph TOPOLOGY is "
                "reconstructed, exactly as twin/nsl_kdd.py does for NSL-KDD."
            ),
        },
        "bouncer": bouncer_metrics,
        "detective": detective_metrics,
        "weight_verification": weight_verification,
    }

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    METRICS_PATH.write_text(json.dumps(full_metrics, indent=2))

    print("\n" + "=" * 70)
    print("UNSW-NB15 EXPERIMENT COMPLETE")
    print(f"Metrics saved to: {METRICS_PATH}")
    print(f"Bouncer weights: {BOUNCER_DIR}")
    print(f"Detective weights: {DETECTIVE_DIR}")
    print("=" * 70)
    return 0


if __name__ == "__main__":
    sys.exit(main())
